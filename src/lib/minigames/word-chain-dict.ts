const wordSet = new Set(WORDS);

export function normalizeWordChainWord(text: string): string {
  return text.trim().normalize("NFC").replace(/\s+/g, "");
}

export function isValidWordChainWord(word: string): boolean {
  const w = normalizeWordChainWord(word);
  if (w.length < 2 || w.length > 12) return false;
  if (!/^[가-힣]+$/.test(w)) return false;
  return wordSet.has(w);
}

export function wordChainNextRequiredChar(currentWord: string | null): string | null {
  if (!currentWord) return null;
  const w = normalizeWordChainWord(currentWord);
  if (!w) return null;
  return w[w.length - 1]!;
}

export function previewWordChainInput(
  word: string,
  currentWord: string | null,
  usedWords: string[]
): { ok: boolean; hint: string | null } {
  const w = normalizeWordChainWord(word);
  if (!w) return { ok: false, hint: null };
  const required = wordChainNextRequiredChar(currentWord);
  if (required && w[0] !== required) {
    return { ok: false, hint: `「${required}」로 시작해야 합니다` };
  }
  if (usedWords.includes(w)) return { ok: false, hint: "이미 사용한 단어입니다" };
  if (!/^[가-힣]+$/.test(w)) return { ok: false, hint: "한글만 입력 가능합니다" };
  if (w.length < 2) return { ok: false, hint: "2글자 이상 입력하세요" };
  if (!isValidWordChainWord(w)) return { ok: false, hint: "사전에 없는 단어입니다" };
  return { ok: true, hint: null };
}

export function validateWordChainMove(
  word: string,
  currentWord: string | null,
  usedWords: string[]
): string | null {
  const w = normalizeWordChainWord(word);
  if (!isValidWordChainWord(w)) return "사전에 없는 단어입니다.";
  if (usedWords.includes(w)) return "이미 사용한 단어입니다.";
  if (currentWord) {
    const required = wordChainNextRequiredChar(currentWord);
    if (required && w[0] !== required) {
      return `「${required}」(으)로 시작하는 단어를 입력하세요.`;
    }
  }
  return null;
}
