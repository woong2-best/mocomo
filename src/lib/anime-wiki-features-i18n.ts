function mapLocale(locale: Locale): Record<string, string> | null {
  if (locale === "en") return EN;
  if (locale === "ja") return JA;
  if (locale === "zh") return ZH;
  return null;
}

function tr(map: Record<string, string> | null, text: string): string {
  if (!map) return text;
  return map[text] ?? text;
}

export function getLocalizedAnimeWikiSections(locale: Locale): WikiFeatureSection[] {
  const map = mapLocale(locale);
  if (!map) return ANIME_WIKI_SECTIONS;

  return ANIME_WIKI_SECTIONS.map((section) => ({
    ...section,
    title: tr(map, section.title),
    example: section.example,
    items: section.items.map((item) => ({
      ...item,
      label: tr(map, item.label),
    })),
    blocks: section.blocks?.map((block) => ({
      title: tr(map, block.title),
      lines: block.lines,
    })),
  }));
}
