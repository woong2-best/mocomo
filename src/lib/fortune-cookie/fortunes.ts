export const FORTUNE_COUNT = FORTUNE_ENTRIES.length;

export function formatCookieSerial(serialNo: number): string {
  return `#COOKIE-${String(Math.max(0, serialNo)).padStart(5, "0")}`;
}

export function pickFortuneIndex(seed: string): number {
  let hash = 2166136261;
  for (let i = 0; i < seed.length; i += 1) {
    hash ^= seed.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return Math.abs(hash) % FORTUNE_COUNT;
}

export function fortuneAt(index: number): FortuneEntry {
  return FORTUNE_ENTRIES[((index % FORTUNE_COUNT) + FORTUNE_COUNT) % FORTUNE_COUNT]!;
}
